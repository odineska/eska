/// Static capability discovery does not open a project or generate IDs.
#[derive(Clone, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CreationCapabilities {
    pub owner_kinds: Vec<MetadataKind>,
    pub kinds: Vec<CreationKind>,
    pub primitive_types: Vec<CreationTypeChoice>,
    pub limits: CreationLimits,
}

/// One owner exposes precisely the kinds, types and languages accepted at this snapshot.
#[derive(Clone, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CreationSchema {
    pub owner: ObjectId,
    pub snapshot: String,
    pub writable: bool,
    pub capabilities: CreationCapabilities,
    pub kinds: Vec<CreationKind>,
    pub references: Vec<CreationReference>,
    pub languages: Vec<CreationLanguage>,
}

/// Domain failures keep client presentation and human localization outside the core.
#[derive(Debug)]
pub enum CreationError {
    Workspace(Box<WorkspaceError>),
    /// Bytes have been committed; callers must inspect rather than repeat creation.
    Committed(Box<WorkspaceError>),
    Edit(EditError),
    Name(NameError),
    Collision(ObjectId),
    UnsupportedOwner(MetadataKind),
    Invalid {
        field: &'static str,
        reason: &'static str,
    },
    Random(getrandom::Error),
}

impl From<WorkspaceError> for CreationError {
    /// Preserve discovery failures at the mutation boundary.
    fn from(value: WorkspaceError) -> Self {
        Self::Workspace(Box::new(value))
    }
}

impl From<EditError> for CreationError {
    /// Reuse existing source, policy and conflict categories.
    fn from(value: EditError) -> Self {
        Self::Edit(value)
    }
}

impl From<super::metadata_workspace::PropertyEditError> for CreationError {
    /// Creation uses the same checked source resolver and cannot discard its error classification.
    fn from(value: super::metadata_workspace::PropertyEditError) -> Self {
        use super::metadata_workspace::PropertyEditError;
        match value {
            PropertyEditError::Workspace(error) => Self::Workspace(error),
            PropertyEditError::Committed(error) => Self::Committed(error),
            PropertyEditError::Edit(error) | PropertyEditError::Related { error, .. } => {
                Self::Edit(error)
            }
        }
    }
}
